"""Side-by-side table of the latest run per (mode, ablation) for a split.

    python -m eval.compare --split dev > results/comparison_dev.md
"""
import argparse
import json

from app.config import RESULTS_DIR

ORDER = [("hybrid", ()), ("rules", ()), ("model", ()), ("hybrid", ("crossdoc",)), ("hybrid", ("registry",)),
         ("rules", ("crossdoc",)), ("rules", ("registry",))]


def latest_runs(split: str) -> dict:
    runs = {}
    for p in sorted(RESULTS_DIR.glob(f"{split}-*.json")):
        d = json.loads(p.read_text())
        if d.get("replay") == "1" or d.get("note", "").startswith("stability"):
            continue
        runs[(d["mode"], tuple(d["ablate"]))] = d       # later files win
    return runs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="dev")
    args = ap.parse_args()
    runs = latest_runs(args.split)
    pct = lambda v: "n/a" if v is None else f"{v * 100:.1f}%"
    keys = [k for k in ORDER if k in runs] + [k for k in runs if k not in ORDER]
    print(f"# Variant comparison, {args.split} set\n")
    print("Generated by `python -m eval.compare`. Each row is the latest results file for that variant.\n")
    print("| Variant | Run id | Decision acc | Fraud recall | False escalation | Field acc | Digital | Scanned | Arabic | $/case |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for k in keys:
        d = runs[k]
        m = d["metrics"]
        name = k[0] + (f" − {'+'.join(k[1])}" if k[1] else "")
        bi = m["by_input"]
        print(f"| {name} | {d['run_id']} | {pct(m['decision_accuracy'])} | {pct(m['fraud_recall'])} | "
              f"{pct(m['false_escalation_rate'])} | {pct(m['field_accuracy'])} | "
              f"{pct(bi.get('digital', {}).get('accuracy'))} | {pct(bi.get('scanned', {}).get('accuracy'))} | "
              f"{pct(bi.get('arabic', {}).get('accuracy'))} | {m['cost_usd_per_case']} |")
    print("\n## Accuracy by scenario\n")
    scen = sorted({s for k in keys for s in runs[k]["metrics"]["by_scenario"]})
    print("| Scenario | " + " | ".join(k[0] + (f" − {'+'.join(k[1])}" if k[1] else "") for k in keys) + " |")
    print("|---|" + "---|" * len(keys))
    for s in scen:
        cells = [pct(runs[k]["metrics"]["by_scenario"].get(s, {}).get("accuracy")) for k in keys]
        n = runs[keys[0]]["metrics"]["by_scenario"].get(s, {}).get("n", "")
        print(f"| {s} (n={n}) | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main()
